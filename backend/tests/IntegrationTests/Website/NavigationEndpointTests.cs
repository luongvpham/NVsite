using System.Net;
using System.Net.Http.Json;
using System.Text.Json;
using Vsite.Application.Website.Dtos;
using Vsite.Domain.Identity;
using Vsite.IntegrationTests.Media;

namespace Vsite.IntegrationTests.Website;

/// <summary>
/// T3 (WEBSITE-007, #113) — <c>getNavigation</c>/<c>saveNavigation</c> qua HTTP thật (routing, auth, Owner filter, binding DTO có
/// kiểu, ProblemDetails, Postgres). R1/R2 qua HTTP, 422 <c>params.errors[].path</c>, Owner-only (#100).
/// </summary>
[Collection(MediaApiCollection.Name)]
public sealed class NavigationEndpointTests
{
    private readonly ShopApiHarness _h;

    public NavigationEndpointTests(MediaApiFactory factory)
    {
        _h = new ShopApiHarness(factory);
    }

    private static string Nav(Guid shopId) => $"/api/shops/{shopId}/website/navigation";

    private static async Task<JsonElement> JsonOf(HttpResponseMessage response)
    {
        var text = await response.Content.ReadAsStringAsync();
        return JsonDocument.Parse(text).RootElement.Clone();
    }

    private async Task<(ShopApiHarness.TestUser Owner, Guid ShopId, WebsiteDto Website, List<PageDto> Pages)> OwnerWithWebsiteAsync()
    {
        var (owner, shopId) = await _h.NewOwnerWithShopAsync();
        var create = await _h.SendAsync(HttpMethod.Post, $"/api/shops/{shopId}/website", owner.Token);
        Assert.Equal(HttpStatusCode.Created, create.StatusCode);
        var website = (await create.Content.ReadFromJsonAsync<WebsiteDto>(ShopApiHarness.Json))!;
        var pages = await _h.SendAsync(HttpMethod.Get, $"/api/shops/{shopId}/website/pages", owner.Token);
        return (owner, shopId, website, (await pages.Content.ReadFromJsonAsync<List<PageDto>>(ShopApiHarness.Json))!);
    }

    private Task<HttpResponseMessage> PutAsync(string token, Guid shopId, string versionJson, string itemsJson) =>
        _h.SendRawJsonAsync(HttpMethod.Put, Nav(shopId), token, $"{{\"version\":{versionJson},\"items\":{itemsJson}}}");

    private static string PageKey(Guid id) => $"page:{id:D}";

    [Fact]
    public async Task Get_before_any_save_is_autogenerated_with_null_version_and_dirty_and_null_url_on_page_items()
    {
        var (owner, shopId, website, _) = await OwnerWithWebsiteAsync();

        var response = await _h.SendAsync(HttpMethod.Get, Nav(shopId), owner.Token);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var json = await JsonOf(response);
        Assert.Equal(JsonValueKind.Null, json.GetProperty("version").ValueKind);
        Assert.True(json.GetProperty("isDirty").GetBoolean());
        var items = json.GetProperty("items").EnumerateArray().ToList();
        Assert.Contains(items, i => i.GetProperty("key").GetString() == PageKey(website.HomePageId));
        Assert.All(items, i =>
        {
            Assert.Equal(JsonValueKind.Null, i.GetProperty("label").ValueKind);
            Assert.False(i.GetProperty("hidden").GetBoolean());
            Assert.Equal(JsonValueKind.Null, i.GetProperty("url").ValueKind); // url chỉ có giá trị ở custom
            Assert.Equal(0, i.GetProperty("children").GetArrayLength());
        });
    }

    [Fact]
    public async Task Put_then_get_round_trips_dirty_and_new_version_differs()
    {
        var (owner, shopId, website, _) = await OwnerWithWebsiteAsync();
        var home = PageKey(website.HomePageId);

        var first = await PutAsync(owner.Token, shopId, "null",
            $$"""[{"key":"{{home}}","label":"Trang chủ","hidden":false,"children":[{"key":"custom","label":"Zalo","url":"https://zalo.me/1","hidden":false}]}]""");
        Assert.Equal(HttpStatusCode.OK, first.StatusCode);
        var firstJson = await JsonOf(first);
        Assert.True(firstJson.GetProperty("isDirty").GetBoolean());
        var v1 = firstJson.GetProperty("version").GetInt64();

        var second = await PutAsync(owner.Token, shopId, v1.ToString(), $$"""[{"key":"{{home}}","hidden":true}]""");
        Assert.Equal(HttpStatusCode.OK, second.StatusCode);
        var v2 = (await JsonOf(second)).GetProperty("version").GetInt64();
        Assert.NotEqual(v1, v2);

        var get = await JsonOf(await _h.SendAsync(HttpMethod.Get, Nav(shopId), owner.Token));
        Assert.Equal(v2, get.GetProperty("version").GetInt64());
        Assert.True(get.GetProperty("isDirty").GetBoolean());
        var firstItem = get.GetProperty("items")[0];
        Assert.Equal(home, firstItem.GetProperty("key").GetString());
        Assert.True(firstItem.GetProperty("hidden").GetBoolean());
    }

    [Fact]
    public async Task Child_custom_item_comes_back_with_url_and_without_nested_children()
    {
        var (owner, shopId, website, _) = await OwnerWithWebsiteAsync();
        var home = PageKey(website.HomePageId);
        var put = await PutAsync(owner.Token, shopId, "null",
            $$"""[{"key":"{{home}}","hidden":false,"children":[{"key":"custom","label":"Gọi","url":"tel:0900000000","hidden":false}]}]""");
        Assert.Equal(HttpStatusCode.OK, put.StatusCode);

        var get = await JsonOf(await _h.SendAsync(HttpMethod.Get, Nav(shopId), owner.Token));
        var child = get.GetProperty("items")[0].GetProperty("children")[0];

        Assert.Equal("custom", child.GetProperty("key").GetString());
        Assert.Equal("tel:0900000000", child.GetProperty("url").GetString());
        Assert.False(child.TryGetProperty("children", out _));
    }

    // Mục con không có `children` trong kiểu (menu một cấp, #113): cháu gửi lên bị bỏ qua như mọi thuộc tính lạ, không 500.
    [Fact]
    public async Task Grandchildren_in_body_are_ignored_not_stored()
    {
        var (owner, shopId, website, _) = await OwnerWithWebsiteAsync();
        var put = await PutAsync(owner.Token, shopId, "null",
            $$"""[{"key":"{{PageKey(website.HomePageId)}}","hidden":false,"children":[{"key":"custom","label":"A","url":"https://a.vn","hidden":false,"children":[{"key":"custom","label":"B","url":"https://b.vn","hidden":false}]}]}]""");
        Assert.Equal(HttpStatusCode.OK, put.StatusCode);

        var get = await JsonOf(await _h.SendAsync(HttpMethod.Get, Nav(shopId), owner.Token));
        var child = Assert.Single(get.GetProperty("items")[0].GetProperty("children").EnumerateArray());
        Assert.False(child.TryGetProperty("children", out _));
        Assert.DoesNotContain("b.vn", get.GetRawText());
    }

    // R2 qua HTTP.
    [Fact]
    public async Task Second_first_save_is_409_NAVIGATION_CONFLICT_with_currentVersion_and_updatedAt()
    {
        var (owner, shopId, website, _) = await OwnerWithWebsiteAsync();
        var items = $$"""[{"key":"{{PageKey(website.HomePageId)}}","hidden":false}]""";

        var tabA = await PutAsync(owner.Token, shopId, "null", items);
        Assert.Equal(HttpStatusCode.OK, tabA.StatusCode);
        var versionA = (await JsonOf(tabA)).GetProperty("version").GetInt64();

        var tabB = await PutAsync(owner.Token, shopId, "null", items);

        Assert.Equal(HttpStatusCode.Conflict, tabB.StatusCode);
        var problem = await JsonOf(tabB);
        Assert.Equal("NAVIGATION_CONFLICT", problem.GetProperty("error_code").GetString());
        Assert.Equal(versionA, problem.GetProperty("params").GetProperty("currentVersion").GetInt64());
        Assert.Equal(JsonValueKind.String, problem.GetProperty("params").GetProperty("updatedAt").ValueKind);
    }

    // R1 + 422 path qua HTTP.
    [Fact]
    public async Task Page_of_another_shop_is_422_with_params_errors_path()
    {
        var a = await OwnerWithWebsiteAsync();
        var b = await OwnerWithWebsiteAsync();

        var response = await PutAsync(a.Owner.Token, a.ShopId, "null",
            $$"""[{"key":"{{PageKey(a.Website.HomePageId)}}","hidden":false},{"key":"{{PageKey(b.Website.HomePageId)}}","hidden":false}]""");

        Assert.Equal(HttpStatusCode.UnprocessableEntity, response.StatusCode);
        var problem = await JsonOf(response);
        Assert.Equal("NAVIGATION_INVALID", problem.GetProperty("error_code").GetString());
        var error = Assert.Single(problem.GetProperty("params").GetProperty("errors").EnumerateArray());
        Assert.Equal("/items/1/key", error.GetProperty("path").GetString());
        Assert.Equal("NAV_PAGE_NOT_FOUND", error.GetProperty("code").GetString());
        Assert.False(string.IsNullOrEmpty(error.GetProperty("message").GetString()));

        // Không ghi gì: vẫn là menu tự sinh.
        var get = await JsonOf(await _h.SendAsync(HttpMethod.Get, Nav(a.ShopId), a.Owner.Token));
        Assert.Equal(JsonValueKind.Null, get.GetProperty("version").ValueKind);
    }

    [Fact]
    public async Task Unsafe_custom_url_in_child_is_422_with_child_path()
    {
        var (owner, shopId, website, _) = await OwnerWithWebsiteAsync();

        var response = await PutAsync(owner.Token, shopId, "null",
            $$"""[{"key":"{{PageKey(website.HomePageId)}}","hidden":false,"children":[{"key":"custom","label":"X","url":"javascript:alert(1)","hidden":false}]}]""");

        Assert.Equal(HttpStatusCode.UnprocessableEntity, response.StatusCode);
        var errors = (await JsonOf(response)).GetProperty("params").GetProperty("errors").EnumerateArray().ToList();
        Assert.Contains(errors, e => e.GetProperty("path").GetString() == "/items/0/children/0/url"
            && e.GetProperty("code").GetString() == "NAV_URL_UNSAFE");
    }

    [Fact]
    public async Task Without_a_website_both_routes_are_404_WEBSITE_NOT_FOUND()
    {
        var (owner, shopId) = await _h.NewOwnerWithShopAsync();

        var get = await _h.SendAsync(HttpMethod.Get, Nav(shopId), owner.Token);
        var put = await PutAsync(owner.Token, shopId, "null", "[]");

        foreach (var response in new[] { get, put })
        {
            Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
            Assert.Equal("WEBSITE_NOT_FOUND", (await JsonOf(response)).GetProperty("error_code").GetString());
        }
    }

    // #100 — Owner-only, đọc lẫn ghi.
    [Theory]
    [InlineData("Customer")]
    [InlineData("Manager")]
    [InlineData("Staff")]
    [InlineData("Accountant")]
    public async Task Non_owner_member_is_403_WEBSITE_OWNER_REQUIRED_on_both_routes(string role)
    {
        var (_, shopId, _, _) = await OwnerWithWebsiteAsync();
        var roleId = role switch
        {
            "Customer" => WellKnownRoles.CustomerId,
            "Manager" => WellKnownRoles.ManagerId,
            "Staff" => WellKnownRoles.StaffId,
            _ => WellKnownRoles.AccountantId,
        };
        var member = await _h.NewMemberAsync(shopId, roleId);

        var get = await _h.SendAsync(HttpMethod.Get, Nav(shopId), member.Token);
        var put = await PutAsync(member.Token, shopId, "null", "[]");

        foreach (var response in new[] { get, put })
        {
            Assert.Equal(HttpStatusCode.Forbidden, response.StatusCode);
            Assert.Equal("WEBSITE_OWNER_REQUIRED", (await JsonOf(response)).GetProperty("error_code").GetString());
        }
    }

    [Fact]
    public async Task Without_token_is_401_and_outsider_is_403_SHOP_ACCESS_DENIED()
    {
        var (_, shopId, _, _) = await OwnerWithWebsiteAsync();
        var outsider = await _h.NewUserAsync();

        Assert.Equal(HttpStatusCode.Unauthorized, (await _h.SendAsync(HttpMethod.Get, Nav(shopId), null)).StatusCode);
        Assert.Equal(HttpStatusCode.Unauthorized, (await _h.SendRawJsonAsync(HttpMethod.Put, Nav(shopId), null, """{"version":null,"items":[]}""")).StatusCode);

        var get = await _h.SendAsync(HttpMethod.Get, Nav(shopId), outsider.Token);
        Assert.Equal(HttpStatusCode.Forbidden, get.StatusCode);
        Assert.Equal("SHOP_ACCESS_DENIED", (await JsonOf(get)).GetProperty("error_code").GetString());
    }

    // #21 — Owner shop A gọi route của shop B: filter chặn (không phải Owner của B), menu B không đổi.
    [Fact]
    public async Task Owner_of_shop_A_cannot_touch_shop_B_menu_through_shop_B_route()
    {
        var a = await OwnerWithWebsiteAsync();
        var b = await OwnerWithWebsiteAsync();

        var response = await PutAsync(a.Owner.Token, b.ShopId, "null", "[]");

        Assert.Equal(HttpStatusCode.Forbidden, response.StatusCode);
        var getB = await JsonOf(await _h.SendAsync(HttpMethod.Get, Nav(b.ShopId), b.Owner.Token));
        Assert.Equal(JsonValueKind.Null, getB.GetProperty("version").ValueKind);
    }
}
