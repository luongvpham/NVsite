        var unknown = await Assert.ThrowsAsync<DocumentInvalidException>(() => Save(requestA, null, PageItem(Guid.NewGuid())));
        Assert.Equal(Errors(ex)[0].Code, Errors(unknown)[0].Code);
        Assert.Equal(0, await RowCount(Cs, a.ShopId));
    }

