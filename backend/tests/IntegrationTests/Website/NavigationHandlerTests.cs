    // ---- R2: concurrency ----

    [Fact]
    public async Task Null_version_when_a_saved_menu_exists_is_409_NAVIGATION_CONFLICT()
    {
        var seeded = await AddWebsiteAsync(Cs);
        await using var tabA = new Request(Cs, seeded.ShopId);
        await using var tabB = new Request(Cs, seeded.ShopId);
        var opened = await Get(tabA); // cả hai tab mở khi chưa có bản lưu
        Assert.Null(opened.Version);

        var saved = await Save(tabB, null, PageItem(seeded.Contact.Id));
        var ex = await Assert.ThrowsAsync<NavigationConflictException>(() => Save(tabA, null, PageItem(seeded.Home.Id)));

        Assert.Equal("NAVIGATION_CONFLICT", ex.ErrorCode);
        Assert.Equal(409, ex.StatusCode);
        var info = Assert.IsType<NavigationConflictParams>(ex.ErrorParams);
        Assert.Equal(saved.Version, info.CurrentVersion);
        Assert.True(info.UpdatedAt > DateTimeOffset.UtcNow.AddMinutes(-5));

        await using var reader = new Request(Cs, seeded.ShopId);
        Assert.Equal(NavItem.PageKey(seeded.Contact.Id), (await Get(reader)).Items[0].Key); // bản của B còn nguyên
    }

