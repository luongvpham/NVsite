    [Fact]
    public async Task Insert_race_unique_violation_23505_is_409_NAVIGATION_CONFLICT_not_500()
    {
        // Tab khác chèn dòng ngay TRƯỚC khi handler INSERT (handler đã thấy "chưa có dòng") ⇒ PK website_id trùng ⇒ 23505.
        var seeded = await AddWebsiteAsync(Cs);
        await using var racing = new Request(Cs, seeded.ShopId, null,
            new InsertNavigationInterceptor(Cs, seeded.ShopId, seeded.Website.Id));

        var ex = await Assert.ThrowsAsync<NavigationConflictException>(() => Save(racing, null, PageItem(seeded.Home.Id)));

        var info = Assert.IsType<NavigationConflictParams>(ex.ErrorParams);
        Assert.NotNull(info.CurrentVersion);
        Assert.Equal(1, await RowCount(Cs, seeded.ShopId));
    }

    [Fact]
    public async Task Two_parallel_first_saves_yield_exactly_one_success_and_a_409()
    {
        var seeded = await AddWebsiteAsync(Cs);
        await using var a = new Request(Cs, seeded.ShopId);
        await using var b = new Request(Cs, seeded.ShopId);

        var results = await Task.WhenAll(
            Attempt(Save(a, null, PageItem(seeded.Home.Id))),
            Attempt(Save(b, null, PageItem(seeded.Contact.Id))));

        Assert.Equal(1, results.Count(r => r is null));
        Assert.Equal("NAVIGATION_CONFLICT", Assert.Single(results.OfType<AppException>()).ErrorCode);
    }

    [Fact]
    public async Task Concurrency_exception_at_SaveChanges_is_409_NAVIGATION_CONFLICT()
    {
        var seeded = await AddWebsiteAsync(Cs);
        long version;
        await using (var setup = new Request(Cs, seeded.ShopId))
        {
            version = (await Save(setup, null, PageItem(seeded.Home.Id))).Version;
        }

        await using var racing = new Request(Cs, seeded.ShopId, null, new BumpNavigationXminInterceptor(Cs, seeded.Website.Id));
        var ex = await Assert.ThrowsAsync<NavigationConflictException>(() => Save(racing, version, PageItem(seeded.Contact.Id)));

        Assert.NotEqual(version, Assert.IsType<NavigationConflictParams>(ex.ErrorParams).CurrentVersion);
    }

