/// <summary>
/// T3 (WEBSITE-007, #113) — <c>GetNavigation</c>/<c>SaveNavigation</c> trên Postgres thật. R1 (trang shop khác/đã xoá ⇒
/// <c>NAV_PAGE_NOT_FOUND</c>, không lộ tồn tại), R2 (hai tab lưu lần đầu / gửi <c>null</c> khi đã có bản / race <c>23505</c> và
/// <c>xmin</c> ⇒ <c>409 NAVIGATION_CONFLICT</c>), G6 (chưa từng lưu ⇒ <c>version: null</c>, <c>isDirty: true</c>).
/// </summary>
