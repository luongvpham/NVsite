    // ---- SAVE: đường vui ----

    [Fact]
    public async Task First_save_with_null_version_inserts_and_returns_version_and_dirty()
    {
        var seeded = await AddWebsiteAsync(Cs);
        await using var request = new Request(Cs, seeded.ShopId);

        var result = await Save(request, null,
            PageItem(seeded.Contact.Id, "  Liên hệ  ", children: ChildCustom("Zalo", "https://zalo.me/123")),
            PageItem(seeded.Home.Id, "   ", hidden: true));

        Assert.True(result.Version > 0);
        Assert.True(result.IsDirty);

        await using var reader = new Request(Cs, seeded.ShopId);
        var nav = await Get(reader);
        Assert.Equal(result.Version, nav.Version);
        Assert.True(nav.IsDirty);
        Assert.Equal(2, nav.Items.Count);
        Assert.Equal(NavItem.PageKey(seeded.Contact.Id), nav.Items[0].Key);
        Assert.Equal("Liên hệ", nav.Items[0].Label); // trim khi lưu (R4)
        var child = Assert.Single(nav.Items[0].Children!);
        Assert.Equal(NavItem.CustomKey, child.Key);
        Assert.Equal("https://zalo.me/123", child.Url);
        Assert.Equal(NavItem.PageKey(seeded.Home.Id), nav.Items[1].Key);
        Assert.Null(nav.Items[1].Label); // nhãn rỗng ⇒ null (dùng tên trang)
        Assert.True(nav.Items[1].Hidden);
    }

