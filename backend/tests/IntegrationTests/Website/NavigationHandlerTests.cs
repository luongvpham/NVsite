    [Fact]
    public async Task Shop_A_never_sees_or_overwrites_shop_B_menu()
    {
        var a = await AddWebsiteAsync(Cs);
        var b = await AddWebsiteAsync(Cs);
        await using (var requestB = new Request(Cs, b.ShopId))
        {
            await Save(requestB, null, PageItem(b.Contact.Id, "Của B"));
        }

        await using var requestA = new Request(Cs, a.ShopId);
        var navA = await Get(requestA);
        Assert.Null(navA.Version); // A chưa từng lưu — không thấy dòng của B
        Assert.DoesNotContain(navA.Items, i => i.Key == NavItem.PageKey(b.Contact.Id));

        await Save(requestA, null, PageItem(a.Home.Id, "Của A"));

        await using var readerB = new Request(Cs, b.ShopId);
        var navB = await Get(readerB);
        Assert.Equal("Của B", navB.Items[0].Label);
    }

    private static async Task<AppException?> Attempt(Task task)
    {
        try
        {
            await task;
            return null;
        }
        catch (AppException ex)
        {
            return ex;
        }
    }

    /// <summary>Chèn một dòng menu từ kết nối khác ngay TRƯỚC khi handler ghi (một lần).</summary>
    private sealed class InsertNavigationInterceptor(string connectionString, Guid shopId, Guid websiteId) : SaveChangesInterceptor
    {
        private bool _done;

        public override async ValueTask<InterceptionResult<int>> SavingChangesAsync(
            DbContextEventData eventData, InterceptionResult<int> result, CancellationToken cancellationToken = default)
        {
            if (!_done)
            {
                _done = true;
                await using var other = NewDb(connectionString, shopId);
                other.NavigationConfigs.Add(NavigationConfig.Create(websiteId, shopId, """{"schemaVersion":1,"items":[]}"""));
                await other.SaveChangesAsync(cancellationToken);
            }

            return result;
        }
    }

    /// <summary>Chạm dòng menu từ kết nối khác ngay TRƯỚC khi handler UPDATE ⇒ <c>xmin</c> lệch ⇒ 0 dòng.</summary>
    private sealed class BumpNavigationXminInterceptor(string connectionString, Guid websiteId) : SaveChangesInterceptor
    {
        public override async ValueTask<InterceptionResult<int>> SavingChangesAsync(
            DbContextEventData eventData, InterceptionResult<int> result, CancellationToken cancellationToken = default)
        {
            await using var other = NewDb(connectionString, null);
            await other.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE navigation_config SET is_dirty = is_dirty WHERE website_id = {websiteId}", cancellationToken);
            return result;
        }
    }
