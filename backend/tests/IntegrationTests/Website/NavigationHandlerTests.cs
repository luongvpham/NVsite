    private string Cs => postgres.ConnectionString;

    public Task InitializeAsync() => MigrateAsync(Cs);

    public Task DisposeAsync() => Task.CompletedTask;

    // ---- helpers ----

    private static Task<NavigationDto> Get(Request r) =>
        new GetNavigationHandler(r.Db, r.Tenant, S.Versioning).Handle(new GetNavigationQuery(), default);

    private static Task<SaveNavigationResultDto> Save(Request r, long? version, params NavigationItemDto[] items) =>
        new SaveNavigationHandler(r.Db, r.Tenant, S.Versioning).Handle(new SaveNavigationCommand(version, items), default);

    private static NavigationItemDto PageItem(Guid pageId, string? label = null, bool hidden = false, params NavigationChildItemDto[] children) =>
        new(NavItem.PageKey(pageId), label, null, hidden, children);

    private static NavigationChildItemDto ChildPage(Guid pageId) => new(NavItem.PageKey(pageId), null, null, false);

    private static NavigationChildItemDto ChildCustom(string? label, string url) => new(NavItem.CustomKey, label, url, false);

    private static NavigationItemDto Custom(string label, string url) => new(NavItem.CustomKey, label, url, false, []);

    private static IReadOnlyList<TreeErrorView> Errors(DocumentInvalidException ex) =>
        ex.Details.Select(e => new TreeErrorView(e.Path, e.Code)).ToList();

    private sealed record TreeErrorView(string Path, string Code);

    private static async Task<int> RowCount(string cs, Guid shopId)
    {
        await using var db = NewDb(cs, shopId);
        return await db.NavigationConfigs.CountAsync();
    }

    // ---- GET: chưa từng lưu (Flow 1, G6) ----

    [Fact]
    public async Task Get_before_any_save_returns_autogenerated_menu_with_null_version_and_dirty()
    {
        var seeded = await AddWebsiteAsync(Cs);
        await using var request = new Request(Cs, seeded.ShopId);

        var nav = await Get(request);

        Assert.Null(nav.Version);
        Assert.True(nav.IsDirty);
        var expected = seeded.Pages
            .Where(p => p.SystemType != SystemType.NotFound)
            .OrderBy(p => p.SortOrder).ThenBy(p => p.Title, StringComparer.Ordinal)
            .Select(p => NavItem.PageKey(p.Id))
            .ToList();
        Assert.Equal(expected, nav.Items.Select(i => i.Key).ToList());
        Assert.DoesNotContain(nav.Items, i => i.Key == NavItem.PageKey(seeded.NotFound.Id));
        Assert.All(nav.Items, i =>
        {
            Assert.False(i.Hidden);
            Assert.Null(i.Label);
            Assert.Null(i.Url);
            Assert.NotNull(i.Children);
            Assert.Empty(i.Children!);
        });
        Assert.Equal(0, await RowCount(Cs, seeded.ShopId)); // đọc không ghi
    }

