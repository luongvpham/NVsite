    [Fact]
    public async Task Save_sets_dirty_even_when_row_was_published()
    {
        var seeded = await AddWebsiteAsync(Cs);
        await using (var request = new Request(Cs, seeded.ShopId))
        {
            await Save(request, null, PageItem(seeded.Home.Id));
            var row = await request.Db.NavigationConfigs.SingleAsync();
            row.MarkPublished();
            await request.Db.SaveChangesAsync();
        }

        await using var tab = new Request(Cs, seeded.ShopId);
        var before = await Get(tab);
        Assert.False(before.IsDirty);

        var result = await Save(tab, before.Version, PageItem(seeded.Home.Id, "Đổi nhãn"));

        Assert.True(result.IsDirty);
        Assert.NotEqual(before.Version, result.Version);
    }

    // ---- Flow 3: trang mới / trang xoá sau khi đã có menu ----

    [Fact]
    public async Task Read_after_save_appends_new_pages_hidden_and_drops_deleted_pages()
    {
        var seeded = await AddWebsiteAsync(Cs);
        await using var request = new Request(Cs, seeded.ShopId);
        var about = await request.CreatePage(new CreatePageCommand("gioi-thieu", "Giới thiệu"));
        await Save(request, null, PageItem(about.Id, children: ChildPage(seeded.Contact.Id)), PageItem(seeded.Home.Id));

        var fresh = await request.CreatePage(new CreatePageCommand("bang-gia", "Bảng giá"));
        await request.DeletePage(about.Id);

        await using var reader = new Request(Cs, seeded.ShopId);
        var nav = await Get(reader);

        // "about" bị xoá ⇒ bỏ cả nhóm con của nó; Contact (con của about) không còn trong menu ⇒ nối cuối, ẩn, cùng trang mới.
        Assert.Equal(NavItem.PageKey(seeded.Home.Id), nav.Items[0].Key);
        Assert.False(nav.Items[0].Hidden);
        Assert.DoesNotContain(nav.Items, i => i.Key == NavItem.PageKey(about.Id));
        var appended = nav.Items.Skip(1).ToList();
        Assert.Contains(appended, i => i.Key == NavItem.PageKey(fresh.Id) && i.Hidden);
        Assert.Contains(appended, i => i.Key == NavItem.PageKey(seeded.Contact.Id) && i.Hidden);
        Assert.DoesNotContain(nav.Items, i => i.Key == NavItem.PageKey(seeded.NotFound.Id));
    }

