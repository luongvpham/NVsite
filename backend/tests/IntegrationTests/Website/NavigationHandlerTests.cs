    [Fact]
    public async Task Page_of_another_shop_is_422_NAV_PAGE_NOT_FOUND_and_nothing_is_written()
    {
        var a = await AddWebsiteAsync(Cs);
        var b = await AddWebsiteAsync(Cs);
